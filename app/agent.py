"""AI Agent module for IRIS: Technical incident reasoning informed by persistent memory."""

import json
import logging
from dataclasses import dataclass, field
from typing import Any, Dict, List, Optional

from memory.recall import RecallMatch, RecallOutput
from utils.config import settings

logger = logging.getLogger("iris.agent")


@dataclass
class InvestigationHypothesis:
    """A root cause hypothesis with confidence score and evidence justification."""
    title: str
    confidence: str  # "High", "Medium", "Low"
    rationale: str
    is_confirmed: bool = False


@dataclass
class InvestigationStep:
    """A diagnostic troubleshooting step."""
    step_number: int
    title: str
    command_or_query: str
    expected_outcome: str


@dataclass
class InvestigationReport:
    """Complete structured incident investigation report generated by the IRIS Agent."""
    incident_id: str
    incident_summary: str
    potential_root_causes: List[InvestigationHypothesis]
    recommended_steps: List[InvestigationStep]
    relevant_previous_incidents: List[RecallMatch]
    suggested_resolution: str
    confidence_assessment: str
    evidence_limitations: str
    ai_provider: str
    is_llm_active: bool
    setup_message: Optional[str] = None


class IncidentAgent:
    """AI agent responsible for incident analysis, diagnostic planning, and memory synthesis."""

    def __init__(self):
        self.provider = settings.LLM_PROVIDER
        self.openai_key = settings.OPENAI_API_KEY
        self.openai_model = settings.OPENAI_MODEL
        self.gemini_key = settings.GEMINI_API_KEY

    def is_llm_configured(self) -> bool:
        """Check if a real LLM API key is present."""
        if self.provider == "openai" and self.openai_key:
            return True
        if self.provider == "gemini" and self.gemini_key:
            return True
        return False

    def investigate(
        self,
        incident_id: str,
        title: str,
        category: str,
        severity: str,
        affected_system: str,
        description: str,
        error_logs: str,
        recalled_memories: RecallOutput
    ) -> InvestigationReport:
        """Run incident investigation combining current symptoms with retrieved historical memory."""
        
        if self.is_llm_configured():
            try:
                return self._investigate_with_openai(
                    incident_id=incident_id,
                    title=title,
                    category=category,
                    severity=severity,
                    affected_system=affected_system,
                    description=description,
                    error_logs=error_logs,
                    recalled_memories=recalled_memories
                )
            except Exception as e:
                logger.error(f"LLM API invocation failed: {e}. Falling back to deterministic local reasoning.")
                return self._investigate_with_local_heuristics(
                    incident_id=incident_id,
                    title=title,
                    category=category,
                    severity=severity,
                    affected_system=affected_system,
                    description=description,
                    error_logs=error_logs,
                    recalled_memories=recalled_memories,
                    setup_note=f"LLM API call failed ({e}). Reverted to local rule-based engine."
                )
        else:
            return self._investigate_with_local_heuristics(
                incident_id=incident_id,
                title=title,
                category=category,
                severity=severity,
                affected_system=affected_system,
                description=description,
                error_logs=error_logs,
                recalled_memories=recalled_memories,
                setup_note="No LLM API credentials configured (OPENAI_API_KEY is empty). Operating in Local Rule-Based Mode."
            )

    def _investigate_with_openai(
        self,
        incident_id: str,
        title: str,
        category: str,
        severity: str,
        affected_system: str,
        description: str,
        error_logs: str,
        recalled_memories: RecallOutput
    ) -> InvestigationReport:
        """Synthesize response using OpenAI with retrieved memories as grounding context."""
        from openai import OpenAI
        client = OpenAI(api_key=self.openai_key, base_url=settings.OPENAI_BASE_URL or None)

        # Build context from recalled memories
        memory_context = ""
        if recalled_memories.matches:
            memory_context = "\n".join([
                f"- [HISTORICAL PRECEDENT {m.incident_id or m.memory_id}]: Title: {m.title} | System: {m.affected_system} | "
                f"Root Cause: {m.root_cause} | Resolution: {m.resolution}"
                for m in recalled_memories.matches
            ])
        else:
            memory_context = "No previous matching incidents found in persistent memory."

        system_prompt = """You are IRIS (Intelligent Incident Response System), a Principal Site Reliability Engineer.
Analyze the incident rigorously using the provided symptoms and historical memory from Hindsight.
Rules:
1. Distinguish strictly between CONFIRMED FACTS, HISTORICAL PRECEDENTS, and AI HYPOTHESES.
2. Do not invent certainty. State evidence limitations clearly.
3. Respond ONLY in valid JSON matching this schema:
{
  "incident_summary": "Concise summary of the current incident",
  "potential_root_causes": [
    {"title": "Cause name", "confidence": "High|Medium|Low", "rationale": "Why this cause is suspected based on logs and past incidents"}
  ],
  "recommended_steps": [
    {"step_number": 1, "title": "Diagnostic check", "command_or_query": "Exact CLI command or SQL", "expected_outcome": "What good vs bad output looks like"}
  ],
  "suggested_resolution": "Immediate mitigation and long-term fix",
  "confidence_assessment": "Clear evaluation of confidence level",
  "evidence_limitations": "Missing logs, telemetry gaps, or uncertain factors"
}"""

        user_content = f"""Current Incident:
- ID: {incident_id}
- Title: {title}
- Category: {category}
- Severity: {severity}
- Affected System: {affected_system}
- Description: {description}
- Error Logs:
{error_logs}

Retrieved Historical Knowledge from Persistent Memory:
{memory_context}
"""

        response = client.chat.completions.create(
            model=self.openai_model,
            messages=[
                {"role": "system", "content": system_prompt},
                {"role": "user", "content": user_content}
            ],
            response_format={"type": "json_object"},
            temperature=0.2
        )

        content = response.choices[0].message.content
        data = json.loads(content)

        hypotheses = [
            InvestigationHypothesis(
                title=h.get("title", ""),
                confidence=h.get("confidence", "Medium"),
                rationale=h.get("rationale", ""),
                is_confirmed=False
            )
            for h in data.get("potential_root_causes", [])
        ]

        steps = [
            InvestigationStep(
                step_number=s.get("step_number", i + 1),
                title=s.get("title", f"Step {i+1}"),
                command_or_query=s.get("command_or_query", "Check system logs"),
                expected_outcome=s.get("expected_outcome", "Normal operational state")
            )
            for i, s in enumerate(data.get("recommended_steps", []))
        ]

        return InvestigationReport(
            incident_id=incident_id,
            incident_summary=data.get("incident_summary", description),
            potential_root_causes=hypotheses,
            recommended_steps=steps,
            relevant_previous_incidents=recalled_memories.matches,
            suggested_resolution=data.get("suggested_resolution", "Review service runbooks and inspect dependent telemetry."),
            confidence_assessment=data.get("confidence_assessment", "Generated via OpenAI LLM grounded on retrieved Hindsight memory."),
            evidence_limitations=data.get("evidence_limitations", "Diagnostic hypothesis requires confirmation via live system metrics."),
            ai_provider=f"OpenAI ({self.openai_model})",
            is_llm_active=True,
            setup_message=None
        )

    def _investigate_with_local_heuristics(
        self,
        incident_id: str,
        title: str,
        category: str,
        severity: str,
        affected_system: str,
        description: str,
        error_logs: str,
        recalled_memories: RecallOutput,
        setup_note: str = ""
    ) -> InvestigationReport:
        """Deterministic technical SRE heuristic synthesis based on symptoms and retrieved memories."""
        
        has_matches = len(recalled_memories.matches) > 0
        top_match = recalled_memories.matches[0] if has_matches else None
        
        # Determine dominant failure pattern
        combined_text = f"{title} {description} {error_logs} {affected_system}".lower()
        
        hypotheses: List[InvestigationHypothesis] = []
        steps: List[InvestigationStep] = []
        suggested_resolution = ""
        
        if "pool" in combined_text or "53300" in combined_text or "connection" in combined_text or "postgres" in combined_text:
            hypotheses.append(InvestigationHypothesis(
                title="Database Connection Pool Exhaustion / Leaking Clients",
                confidence="High" if (has_matches and "pool" in top_match.title.lower()) else "Medium",
                rationale="Symptoms indicate active clients exceeded allowed server connection slots (SQLSTATE 53300). " +
                          (f"Historical incident {top_match.incident_id} experienced identical connection saturation." if has_matches else "")
            ))
            hypotheses.append(InvestigationHypothesis(
                title="Unreleased Idle in Transaction Handles in Application Tier",
                confidence="Medium",
                rationale="Applications opening database transactions without guaranteed commit/rollback or release blocks."
            ))
            hypotheses.append(InvestigationHypothesis(
                title="Client Retry Storm Amplification",
                confidence="Low",
                rationale="Upstream microservice retries compounding connection pressure during response latency spikes."
            ))

            steps.append(InvestigationStep(
                step_number=1,
                title="Query Active Database Backend Connections",
                command_or_query="SELECT count(*), state, usename, client_addr FROM pg_stat_activity GROUP BY state, usename, client_addr;",
                expected_outcome="Identify count of 'idle in transaction' vs 'active' queries and originating client pod IPs."
            ))
            steps.append(InvestigationStep(
                step_number=2,
                title="Emergency Terminate Stalled Idle Transactions",
                command_or_query="SELECT pg_terminate_backend(pid) FROM pg_stat_activity WHERE state = 'idle in transaction' AND state_change < now() - INTERVAL '3 minutes';",
                expected_outcome="Immediate release of held connection slots to restore cluster responsiveness."
            ))
            steps.append(InvestigationStep(
                step_number=3,
                title="Verify Connection Pooler (PgBouncer/Proxy) Health",
                command_or_query="SHOW POOLS; SHOW CLIENTS;",
                expected_outcome="Verify if client queue is draining or if max_client_conn threshold is saturated."
            ))

            if has_matches and top_match.resolution:
                suggested_resolution = (
                    f"**Historical Proven Fix (from {top_match.incident_id}):** {top_match.resolution}\n\n"
                    f"**Immediate Action:** Terminate orphaned transactions on `{affected_system}` and configure PgBouncer transaction-level pooling with capped client pools."
                )
            else:
                suggested_resolution = "Deploy connection pooler (PgBouncer) in transaction mode, cap client connection pools to 10 connections per container, and enforce 5-second query timeouts."

        elif "oom" in combined_text or "memory" in combined_text or "redis" in combined_text:
            hypotheses.append(InvestigationHypothesis(
                title="Memory Limit Reached / Inadequate Eviction Policy",
                confidence="High" if (has_matches and "redis" in top_match.title.lower()) else "Medium",
                rationale="Service hit configured maxmemory boundary. Eviction policy may fail if keys lack TTL."
            ))
            hypotheses.append(InvestigationHypothesis(
                title="Unbounded Key Ingestion / Missing TTL",
                confidence="Medium",
                rationale="Producers inserting telemetry or session keys without expiration."
            ))

            steps.append(InvestigationStep(
                step_number=1,
                title="Inspect Redis Memory & Eviction Counters",
                command_or_query="redis-cli INFO memory | grep -E 'used_memory_human|maxmemory_human|evicted_keys'",
                expected_outcome="Determine whether memory is at 100% capacity and if eviction is actively succeeding."
            ))
            steps.append(InvestigationStep(
                step_number=2,
                title="Identify Largest Keys and Pattern Distribution",
                command_or_query="redis-cli --bigkeys",
                expected_outcome="Identify key prefixes consuming highest byte volume without TTL."
            ))

            if has_matches and top_match.resolution:
                suggested_resolution = f"**Historical Fix (from {top_match.incident_id}):** {top_match.resolution}"
            else:
                suggested_resolution = "Switch maxmemory-policy to 'allkeys-lru' and enforce strict TTL on all written keys."

        elif "cert" in combined_text or "ssl" in combined_text or "tls" in combined_text:
            hypotheses.append(InvestigationHypothesis(
                title="TLS Certificate Expiration / Challenge Failure",
                confidence="High",
                rationale="Client TLS handshake aborted due to expired or untrusted certificate chain."
            ))
            steps.append(InvestigationStep(
                step_number=1,
                title="Verify Certificate Expiration Date",
                command_or_query="openssl s_client -connect <host>:443 -servername <host> | openssl x509 -noout -dates",
                expected_outcome="Check validity window start and end timestamps."
            ))
            suggested_resolution = "Re-issue certificate via DNS-01 ACME challenge and verify ingress controller reload."

        else:
            hypotheses.append(InvestigationHypothesis(
                title=f"Subsystem Instability in {affected_system}",
                confidence="Medium",
                rationale="Error logs and description point to abnormal state transitions in the target service."
            ))
            steps.append(InvestigationStep(
                step_number=1,
                title="Extract Recent Exception Stack Traces",
                command_or_query=f"kubectl logs -l app={affected_system.lower()} --tail=200 --timestamps",
                expected_outcome="Locate timestamp of initial unhandled fault."
            ))
            suggested_resolution = "Check service logs and health endpoints, verify dependencies, and follow standard on-call runbook."

        summary = (
            f"Incident reported on **{affected_system}** with severity **{severity}**. "
            f"Analyzed {len(hypotheses)} potential failure hypotheses. "
            + (f"Correlated with {len(recalled_memories.matches)} historical incident precedents retrieved from persistent memory."
               if has_matches else "No identical past incidents recorded in memory yet.")
        )

        return InvestigationReport(
            incident_id=incident_id,
            incident_summary=summary,
            potential_root_causes=hypotheses,
            recommended_steps=steps,
            relevant_previous_incidents=recalled_memories.matches,
            suggested_resolution=suggested_resolution,
            confidence_assessment="Local SRE Knowledge Engine (Heuristic reasoning based on system error patterns and memory bank precedents).",
            evidence_limitations="Hypotheses are preliminary AI/diagnostic evaluations and require verification against real telemetry.",
            ai_provider="Local SRE Knowledge Engine",
            is_llm_active=False,
            setup_message=setup_note
        )


# Global agent instance
incident_agent = IncidentAgent()
